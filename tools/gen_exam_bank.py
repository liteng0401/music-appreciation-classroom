_TRAILING = re.compile(r",(\s*[}\]])")


def load_js(path, var):
    src = open(path, encoding="utf-8").read()
    frag = src[src.index("{", src.index(var)):]
    return json.JSONDecoder().raw_decode(_TRAILING.sub(r"\1", frag))[0]


