def build():
    rng = random.Random(SEED)
    data = load_js(os.path.join(ROOT, "data.js"), "COURSE_DATA")
    amap = load_js(os.path.join(ROOT, "audio.js"), "AUDIO_MAP")
    units = data["units"]
    order = [u["id"] for u in units]

    # 全局候选池（干扰项用）
    all_authors = [w["author"] for u in units for w in u["works"]]
    all_genres = [w["genre"] for u in units for w in u["works"]]
    all_names = [w["name"] for u in units for w in u["works"]]
    origins = defaultdict(list)
    for u in units:
        for w in u["works"]:
            val, kind = origin_of(w)
            if val:
                origins[kind].append(val)

    bank, report = {}, []
    for ui, u in enumerate(units):
        uid = u["id"]
        works = u["works"]
        secs = sec_of(u["title"])
        qs = []
        # 邻居单元，用于凑干扰项
        sib = [order[j] for j in (ui - 1, ui + 1) if 0 <= j < len(order)]
        sib_authors = [w["author"] for s in sib for w in
                       next(x for x in units if x["id"] == s)["works"]]
        sib_genres = [w["genre"] for s in sib for w in
                      next(x for x in units if x["id"] == s)["works"]]
        sib_names = [w["name"] for s in sib for w in
                     next(x for x in units if x["id"] == s)["works"]]
        sib_concepts = [c["term"] for s in sib for c in
                        (next(x for x in units if x["id"] == s).get("concepts") or [])]
        sib_concepts += ["调式", "曲式", "节拍", "速度", "音色", "织体"]

        # ① 作品 → 作曲家 / 出处 / 编曲
        for w in works:
            d = pick_distractors(w["author"], [[x["author"] for x in works], sib_authors, all_authors], rng)
            if not d:
                continue
            qs.append(make("%s的作曲（词曲／出处／编曲）是？" % wtitle(w["name"]), w["author"], d,
                           "作品辨识", "%s — %s；体裁：%s。" % (wtitle(w["name"]), w["author"], w["genre"]),
                           uid, rng, sec=section_for(secs, w)))

        # ② 作品 → 体裁 / 行当 / 音乐形式
        for w in works:
            d = pick_distractors(w["genre"], [[x["genre"] for x in works], sib_genres, all_genres], rng)
            if not d:
                continue
            qs.append(make("%s的体裁（音乐形式／行当板式）是？" % wtitle(w["name"]), w["genre"], d,
                           "体裁辨识", "%s — %s。" % (wtitle(w["name"]), w["genre"]), uid, rng,
                           sec=section_for(secs, w)))

        # ③ 作品 → 产地（国别 / 民族 / 地区）
        for w in works:
            val, kind = origin_of(w)
            if not val:
                continue
            d = pick_distractors(val, [origins[kind]], rng)
            if not d:
                continue
            if kind == "民族":
                stem = "%s属于哪个民族的音乐？" % wtitle(w["name"])
            elif kind == "地区":
                stem = "%s是哪个地区的民歌（民间乐曲）？" % wtitle(w["name"])
            else:
                stem = "%s是下列哪一国家的音乐作品？" % wtitle(w["name"])
            qs.append(make(stem, val, d, "产地辨识",
                           "%s — %s。" % (wtitle(w["name"]), w["author"]), uid, rng,
                           sec=section_for(secs, w)))

        # ④ 听辨：放音频 → 是哪部作品
        with_audio = [w for w in works if (uid + "|" + w["name"]) in amap]
        for w in with_audio:
            others = [x["name"] for x in works if x["name"] != w["name"]]
            d = pick_distractors(w["name"], [others, sib_names, all_names], rng)
            if not d:
                continue
            qs.append(make("聆听音频片段，这段音乐出自下列哪部作品？", w["name"], d,
                           "听辨", "音频对应 %s — %s；体裁：%s。" % (wtitle(w["name"]), w["author"], w["genre"]),
                           uid, rng, audio=amap[uid + "|" + w["name"]], sec=section_for(secs, w)))

        # ⑤ 概念 → 术语（干扰项必须与正确项同类：作品名配作品名、人名配人名、概念配概念）
        by_shape = defaultdict(list)
        for c in (u.get("concepts") or []):
            by_shape[shape_of(c["term"])].append(c["term"])
        for s_ in sib:
            for c in (next(x for x in units if x["id"] == s_).get("concepts") or []):
                by_shape[shape_of(c["term"])].append(c["term"])
        for c in (u.get("concepts") or []):
            cue = brief(c["def"])
            term = c["term"]
            if not cue or len(cue) < 10 or term in cue:
                continue
            # 「叶旭全、蒋开儒词，王佑贵曲」这类纯署名条目当题干没有考查意义，跳过
            if "《" not in cue and len(cue) <= 26 and cue.endswith(("曲", "词", "词曲")):
                continue
            d = pick_distractors(term, [by_shape[shape_of(term)], sib_concepts], rng)
            if not d:
                continue
            qs.append(make("「%s」描述的是下列哪一音乐概念？" % cue, term, d,
                           "概念理解", "%s — %s" % (term, brief(c["def"], 90)), uid, rng,
                           sec=section_for(secs)))

        # ⑥ 手写高阶题
        for tag, stem, correct, distr, exp in CURATED.get(uid, []):
            assert correct not in distr, (uid, stem)
            assert len(distr) == 3, (uid, stem)
            qs.append(make(stem, correct, distr, tag, exp, uid, rng, sec=section_for(secs)))

        # 去重（题干+答案相同视为重复），按题型优先级保留，并限制单单元题量
        seen, uniq = set(), []
        for q in qs:
            k = (q["q"], q["options"][q["answer"]])
            if k in seen:
                continue
            seen.add(k)
            uniq.append(q)
        rng.shuffle(uniq)
        uniq.sort(key=lambda q: PRIORITY.get(q["tag"], 9))
        uniq = uniq[:CAP]
        rng.shuffle(uniq)
        bank[uid] = uniq
        report.append((uid, len(uniq)))

    return bank, report


def validate(bank):
    """全量自检：任何一条不达标就报错，避免"页面能显示但内容是错的"这类静默缺陷。"""
    errs = []
    tags, ans_dist, audios = Counter(), Counter(), 0
    for uid, qs in bank.items():
        if not qs:
            errs.append("%s 无题目" % uid)
        for i, q in enumerate(qs):
            where = "%s#%d" % (uid, i)
            for k in ("q", "options", "answer", "explain", "tag"):
                if k not in q:
                    errs.append("%s 缺字段 %s" % (where, k))
            opts = q.get("options") or []
            if len(opts) != 4:
                errs.append("%s 选项数=%d" % (where, len(opts)))
            if len(set(opts)) != len(opts):
                errs.append("%s 选项重复：%s" % (where, opts))
            if not isinstance(q.get("answer"), int) or not 0 <= q["answer"] < len(opts):
                errs.append("%s 答案下标非法：%r" % (where, q.get("answer")))
            a = q["q"]
            if not a or not a.endswith(("？", "?")):
                errs.append("%s 题干没以问号结尾" % where)
            # 占位符/模板残留：教材原文里本来就有〔奥〕、[德] 这类写法，不能误伤，所以只查这些
            for bad in ("mistake", "None", "undefined", "NaN", "%s", "{", "}", "TODO"):
                if bad in a or any(bad in str(o) for o in opts):
                    errs.append("%s 含占位/异常字符 %r" % (where, bad))
            # 泄漏检查：正确答案的文本不应原样出现在题干里
            if opts and opts[q["answer"]] in a:
                errs.append("%s 题干泄漏答案" % where)
            tags[q["tag"]] += 1
            ans_dist[q["answer"]] += 1
            if q.get("audio"):
                audios += 1
                if not os.path.exists(os.path.join(ROOT, q["audio"])):
                    errs.append("%s 音频不存在：%s" % (where, q["audio"]))
    return errs, tags, ans_dist, audios


