REGION_HINT = {"印度", "布隆迪", "苏格兰", "爱尔兰", "秘鲁", "阿根廷"}


def origin_of(work):
    """从 works 的 author 字段抽取「产地」，返回 (值, 类别)；抽不出返回 (None, None)。"""
    a = work.get("author", "")
    m = re.match(r"^〔([^〕]+)〕", a)
    if m:
        code = m.group(1)
        if code in COUNTRY:
            return COUNTRY[code], "国别"
        if "—" in code or "-" in code:
            first = re.split(r"[—\-]", code)[0]
            if first in COUNTRY:
                return COUNTRY[first], "国别"
    m = re.match(r"^([\u4e00-\u9fa5]{2,6})（([^）]+)）", a)
    if m and m.group(1) in REGION_HINT:
        return m.group(1), "国别"
    m = re.match(r"^([\u4e00-\u9fa5]{2,8}?)(族)(?:民歌|大歌|民间乐曲|民间歌舞)", a)
    if m:
        return m.group(1) + "族", "民族"
    m = re.match(r"^([\u4e00-\u9fa5]{2,4})(?<!族)民歌$", a)
    if m:
        return m.group(1), "地区"
    if a.endswith("民间乐曲") and len(a) <= 8:
        return a[:-4], "地区"
    return None, None


def wtitle(name):
    """作品名有的自带书名号（如「《广陵散》」），有的没有，统一避免出现《《…》》。"""
    n = (name or "").strip()
    return n if n.startswith("《") else "《%s》" % n


def brief(text, limit=58):
    """把一段带页码引用的长文本压成一句干净的话。"""
    t = re.sub(r"（书第[^）]*页[^）]*）", "", text or "")
    t = re.split(r"[；。]", t)[0].strip(" ，、;；")
    return t if len(t) <= limit else t[:limit].rstrip(" ，、") + "…"


def pick_distractors(correct, pools, rng, n=3):
    """按优先级从候选池组里挑 n 个干扰项。

    pools 是「池子列表」，从前往后取**第一个够用的池子**——不能把所有池子拼起来再随机抽，
    否则本单元的同类干扰项会被别的单元稀释（听辨题就会变成
    「第九交响曲 vs 幸福歌 vs 广陵散」这种一眼排除的题）。全都凑不够才返回 None。
    """
    for pool in pools:
        cand = [x for x in dict.fromkeys(pool) if x and x != correct]
        if len(cand) >= n:
            return rng.sample(cand, n)
    return None


def shape_of(term):
    """判断一个「概念」到底是作品名、人名还是抽象概念 —— 干扰项必须同类，
    否则会出现「影视音乐的定义」配「柴科夫斯基」这种一眼假选项。"""
    if "《" in term:
        return "work"
    if "（" in term and re.search(r"[A-Za-z]", term):
        return "person"
    return "concept"


