def sec_of(title):
    """下篇单元标题里带「（第X节 … · 第Y节 …）」，抽出节列表；上篇没有节划分，返回 []。"""
    m = re.search(r"（(第[一二三四五六七八九十百]+节[^）]*)）", title)
    if not m:
        return []
    return [s.strip() for s in m.group(1).split("·") if s.strip()]


def section_for(secs, work=None):
    """给一道题定位到「节」。

    节的标题形如「第二十六节 舒伯特」「第三十节 斯美塔那与西贝柳斯」，
    把后半截的作曲家/主题词拿去和作品比对，能精确到节就精确到节；
    整个单元只有一节时直接用那一节；多节但匹配不上则返回 None（不硬猜）。
    """
    if not secs:
        return None
    if len(secs) == 1:
        return secs[0]
    if work:
        # 三段线索依次变松：① 作者/曲名/体裁里的关键词命中节标题
        # ② 反过来，节标题里出现作品名的片段（节标题常是主题式，如「高山流水志家国」对应《流水》）
        hay = " ".join([work.get("author", ""), work.get("name", ""), work.get("genre", "")])
        clean = re.sub(r"[《》（）()·]", "", work.get("name", ""))
        for s in secs:
            m = re.match(r"第[一二三四五六七八九十百]+节\s*(.+)$", s)
            if not m:
                continue
            title = m.group(1)
            for key in re.split(r"与|、|和", title):
                key = key.strip()
                if key and key in hay:
                    return s
            if len(clean) >= 2 and clean in title:
                return s
            if len(clean) >= 4:
                for n in (2, 3):
                    for k in range(len(clean) - n + 1):
                        if clean[k:k + n] in title:
                            return s
    return None


def make(stem, correct, distractors, tag, explain, unit, rng, audio=None, sec=None):
    opts = [correct] + list(distractors)
    rng.shuffle(opts)
    q = {"type": "choice", "tag": tag, "q": stem, "options": opts,
         "answer": opts.index(correct), "explain": explain}
    if audio:
        q["audio"] = audio
    q["unit"] = unit
    if sec:
        q["sec"] = sec
    return q


